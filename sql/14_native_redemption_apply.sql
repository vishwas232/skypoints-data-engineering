INSERT INTO {{ns}}.REDEMPTION_CHANGE_AUDIT
 (CHANGE_ID,TRANSACTION_KEY,OLD_FACT_HASH,NEW_FACT_HASH,RUN_ID,BATCH_ID)
WITH incoming AS (
 SELECT * FROM {{ns}}.STG_REDEMPTION_RECORD
 WHERE BATCH_ID=$BATCH_ID AND RECORD_KIND='ITEM' AND VALIDATION_STATUS='VALID'
 QUALIFY ROW_NUMBER() OVER(PARTITION BY TRANSACTION_KEY ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RECORD_ID DESC)=1
)
SELECT SHA2($RUN_ID||s.TRANSACTION_KEY,256),s.TRANSACTION_KEY,t.FACT_HASH,s.FACT_HASH,$RUN_ID,s.BATCH_ID
FROM incoming s JOIN {{ns}}.REDEMPTION_TRANSACTION t USING(TRANSACTION_KEY)
WHERE s.FACT_HASH<>t.FACT_HASH AND
 (s.SOURCE_UPDATE_TS>t.SOURCE_UPDATE_TS OR (s.SOURCE_UPDATE_TS=t.SOURCE_UPDATE_TS AND s.SOURCE_SEQUENCE>t.SOURCE_SEQUENCE));

MERGE INTO {{ns}}.REDEMPTION_TRANSACTION t USING (
 SELECT TRANSACTION_KEY,SOURCE_SYSTEM,SOURCE_MEMBER_ID,GLOBAL_MEMBER_ID,TXN_ID,TXN_DATE,PARTNER,
 MILES_REDEEMED,STATUS,FEED_DATE,SOURCE_UPDATE_TS,SOURCE_SEQUENCE,FACT_HASH,RECORD_ID AS SOURCE_RECORD_ID,
 RAW_RECORD_ID,BATCH_ID AS LAST_BATCH_ID,CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS UPDATED_AT
 FROM {{ns}}.STG_REDEMPTION_RECORD WHERE BATCH_ID=$BATCH_ID AND RECORD_KIND='ITEM' AND VALIDATION_STATUS='VALID'
 QUALIFY ROW_NUMBER() OVER(PARTITION BY TRANSACTION_KEY ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RECORD_ID DESC)=1
) s ON t.TRANSACTION_KEY=s.TRANSACTION_KEY
WHEN MATCHED AND (s.SOURCE_UPDATE_TS>t.SOURCE_UPDATE_TS OR
 (s.SOURCE_UPDATE_TS=t.SOURCE_UPDATE_TS AND s.SOURCE_SEQUENCE>t.SOURCE_SEQUENCE)) THEN UPDATE ALL BY NAME
WHEN NOT MATCHED THEN INSERT ALL BY NAME;
