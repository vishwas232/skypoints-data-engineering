-- Read-only teaching/demo queries. Render {{ns}} through the validated namespace.
SELECT SOURCE_FILE,FEED_TYPE,STATUS,INPUT_ROWS,FILE_SHA256 FROM {{ns}}.INGEST_BATCH ORDER BY STARTED_AT;
SELECT MEMBER_NAME,SOURCE_MEMBER_ID,ENROLLMENT_DATE,LAST_FLIGHT_DATE,DOB,AGE,STALE_MEMBER,
 COUNTRY_CODE,IS_ACTIVE,VALIDATION_STATUS,VALIDATION_ERRORS
FROM {{ns}}.STG_MEMBER_PROFILE ORDER BY BATCH_ID,RAW_RECORD_ID;
SELECT MEMBER_NAME,GLOBAL_MEMBER_ID,COUNTRY_CODE,AGE,STALE_MEMBER,AS_OF_DATE
FROM {{ns}}.MEMBER_CURRENT ORDER BY GLOBAL_MEMBER_ID;
SELECT GLOBAL_MEMBER_ID,FROM_COUNTRY,TO_COUNTRY,SOURCE_UPDATE_TS FROM {{ns}}.COUNTRY_MOVEMENT_AUDIT ORDER BY RECORDED_AT;
SELECT MEMBER_NAME,TXN_ID,MILES_REDEEMED,STATUS,CURRENT_COUNTRY_CODE FROM {{ns}}.REDEMPTION_MEMBER_DETAIL ORDER BY TXN_ID;
SELECT FEED_TYPE,INPUT_ROWS,ACCEPTED_ROWS,REJECTED_ROWS,WINNING_ROWS,REPLAY_ROWS,DOCUMENT_ROWS,REJECTED_DOCUMENTS
FROM {{ns}}.PIPELINE_RUN ORDER BY COMPLETED_AT;
SELECT FEED_TYPE,RECORD_KIND,ERROR_CODES,COUNT(*) AS REJECTS FROM {{ns}}.REJECTED_RECORD GROUP BY FEED_TYPE,RECORD_KIND,ERROR_CODES;
SELECT PHASE,STATUS,ERROR_CATEGORY,COUNT(*) AS ATTEMPTS FROM {{ns}}.PIPELINE_ATTEMPT GROUP BY PHASE,STATUS,ERROR_CATEGORY;
