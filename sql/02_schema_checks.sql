-- SkyPoints Phase 2 - run after 01_create_tables.sql in the same database.
USE SCHEMA SKYPOINTS;

-- Expect 14 tables, all listed below.
SELECT TABLE_NAME, ROW_COUNT
FROM INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'SKYPOINTS' AND TABLE_TYPE = 'BASE TABLE'
ORDER BY TABLE_NAME;

-- Verify key columns (AGE, STALE_MEMBER, SOURCE_SEQUENCE) exist in staging.
SELECT TABLE_NAME, COLUMN_NAME, DATA_TYPE, IS_NULLABLE
FROM INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA = 'SKYPOINTS'
  AND TABLE_NAME IN ('STG_MEMBER_PROFILE', 'MEMBER_CURRENT', 'MEMBER_IDENTITY_MAP')
ORDER BY TABLE_NAME, ORDINAL_POSITION;

-- For a new schema this should return 0 rows initially.
SELECT 'RAW_MEMBER_PROFILE' AS TABLE_NAME, COUNT(*) AS ROWS_LOADED FROM RAW_MEMBER_PROFILE
UNION ALL SELECT 'STG_MEMBER_PROFILE', COUNT(*) FROM STG_MEMBER_PROFILE
UNION ALL SELECT 'MEMBER_CURRENT', COUNT(*) FROM MEMBER_CURRENT
UNION ALL SELECT 'REDEMPTION_TRANSACTION', COUNT(*) FROM REDEMPTION_TRANSACTION;
