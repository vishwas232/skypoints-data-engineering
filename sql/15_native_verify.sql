-- Zero-row invariants. VERIFY_BATCH='' means a full scheduled reconciliation.
SELECT BATCH_ID FROM {{ns}}.INGEST_BATCH WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 GROUP BY BATCH_ID HAVING COUNT(*)<>1;

WITH raw AS (
 SELECT RAW_RECORD_ID,BATCH_ID FROM {{ns}}.RAW_MEMBER_PROFILE
 UNION ALL SELECT RAW_RECORD_ID,BATCH_ID FROM {{ns}}.RAW_REDEMPTION_FEED
)
SELECT RAW_RECORD_ID FROM raw WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 GROUP BY RAW_RECORD_ID HAVING COUNT(*)<>1;

SELECT GLOBAL_MEMBER_ID FROM {{ns}}.MEMBER_CURRENT
 WHERE $VERIFY_BATCH='' OR GLOBAL_MEMBER_ID IN
 (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH)
 GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*)<>1;

SELECT TRANSACTION_KEY FROM {{ns}}.REDEMPTION_TRANSACTION
 WHERE $VERIFY_BATCH='' OR TRANSACTION_KEY IN
 (SELECT TRANSACTION_KEY FROM {{ns}}.STG_REDEMPTION_RECORD WHERE BATCH_ID=$VERIFY_BATCH)
 GROUP BY TRANSACTION_KEY HAVING COUNT(*)<>1;

SELECT RAW_RECORD_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 GROUP BY RAW_RECORD_ID HAVING COUNT(*)<>1;

SELECT RECORD_ID FROM {{ns}}.STG_REDEMPTION_RECORD WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 GROUP BY RECORD_ID HAVING COUNT(*)<>1;

SELECT RUN_ID FROM {{ns}}.PIPELINE_RUN WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 GROUP BY RUN_ID HAVING COUNT(*)<>1;

SELECT RUN_ID FROM {{ns}}.PIPELINE_RUN WHERE ($VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH) AND
 (STATUS<>'COMPLETED' OR INPUT_ROWS<>ACCEPTED_ROWS+REJECTED_ROWS OR ACCEPTED_ROWS<>WINNING_ROWS+REPLAY_ROWS
 OR REJECTED_ROWS<0 OR REPLAY_ROWS<0 OR REJECTED_DOCUMENTS<0 OR REJECTED_DOCUMENTS>DOCUMENT_ROWS);

WITH raw AS (
 SELECT BATCH_ID,COUNT(*) AS N,'MEMBER' AS F FROM {{ns}}.RAW_MEMBER_PROFILE GROUP BY BATCH_ID
 UNION ALL SELECT BATCH_ID,COUNT(*),'REDEMPTION' FROM {{ns}}.RAW_REDEMPTION_FEED GROUP BY BATCH_ID
)
SELECT b.BATCH_ID FROM {{ns}}.INGEST_BATCH b LEFT JOIN raw r ON b.BATCH_ID=r.BATCH_ID AND b.FEED_TYPE=r.F
WHERE ($VERIFY_BATCH='' OR b.BATCH_ID=$VERIFY_BATCH) AND b.INPUT_ROWS<>COALESCE(r.N,0);

WITH latest AS (
 SELECT * FROM {{ns}}.PIPELINE_RUN WHERE $VERIFY_BATCH='' OR BATCH_ID=$VERIFY_BATCH
 QUALIFY ROW_NUMBER() OVER(PARTITION BY BATCH_ID ORDER BY COMPLETED_AT DESC,RUN_ID DESC)=1
), staged AS (
 SELECT BATCH_ID,COUNT(*) AS N,COUNT_IF(VALIDATION_STATUS='VALID') AS V FROM {{ns}}.STG_MEMBER_PROFILE GROUP BY BATCH_ID
 UNION ALL SELECT BATCH_ID,COUNT(*),COUNT_IF(VALIDATION_STATUS='VALID') FROM {{ns}}.STG_REDEMPTION_RECORD WHERE RECORD_KIND='ITEM' GROUP BY BATCH_ID
)
SELECT l.RUN_ID FROM latest l LEFT JOIN staged s ON l.BATCH_ID=s.BATCH_ID
WHERE l.INPUT_ROWS<>COALESCE(s.N,0) OR l.ACCEPTED_ROWS<>COALESCE(s.V,0);

WITH stages AS (
 SELECT RAW_RECORD_ID AS RID,RAW_RECORD_ID,BATCH_ID,VALIDATION_STATUS FROM {{ns}}.STG_MEMBER_PROFILE
 UNION ALL SELECT RECORD_ID,RAW_RECORD_ID,BATCH_ID,VALIDATION_STATUS FROM {{ns}}.STG_REDEMPTION_RECORD
)
SELECT s.RID FROM stages s LEFT JOIN {{ns}}.REJECTED_RECORD q ON s.RID=q.REJECTION_ID AND s.BATCH_ID=q.BATCH_ID
WHERE $VERIFY_BATCH='' OR s.BATCH_ID=$VERIFY_BATCH
GROUP BY s.RID,s.VALIDATION_STATUS
HAVING (s.VALIDATION_STATUS='VALID' AND COUNT(q.REJECTION_ID)<>0)
 OR (s.VALIDATION_STATUS='REJECTED' AND COUNT(q.REJECTION_ID)<>1);

SELECT c.GLOBAL_MEMBER_ID FROM {{ns}}.MEMBER_CURRENT c
LEFT JOIN {{ns}}.STG_MEMBER_PROFILE s ON c.WINNER_RAW_RECORD_ID=s.RAW_RECORD_ID
WHERE ($VERIFY_BATCH='' OR c.GLOBAL_MEMBER_ID IN (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH))
AND (s.RAW_RECORD_ID IS NULL OR s.VALIDATION_STATUS<>'VALID' OR c.FACT_HASH<>s.FACT_HASH
 OR c.FACT_HASH<>SHA2(TO_JSON(ARRAY_CONSTRUCT(c.SOURCE_SYSTEM,c.SOURCE_MEMBER_ID,c.GLOBAL_MEMBER_ID,c.MEMBER_NAME,
 c.ENROLLMENT_DATE,c.LAST_FLIGHT_DATE,c.TIER_CODE,c.AGENT_NAME,c.STATE_CODE,c.COUNTRY_CODE,c.POST_CODE,c.DOB,c.IS_ACTIVE)),256)
 OR c.AGE IS DISTINCT FROM {{ns}}.AGE_ON(c.DOB,c.AS_OF_DATE)
 OR c.STALE_MEMBER IS DISTINCT FROM (DATEDIFF(day,c.LAST_FLIGHT_DATE,c.AS_OF_DATE)>90));

WITH latest AS (
 SELECT * FROM {{ns}}.STG_MEMBER_PROFILE WHERE VALIDATION_STATUS='VALID'
 AND ($VERIFY_BATCH='' OR GLOBAL_MEMBER_ID IN (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH))
 QUALIFY ROW_NUMBER() OVER(PARTITION BY GLOBAL_MEMBER_ID ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RAW_RECORD_ID DESC)=1
)
SELECT s.GLOBAL_MEMBER_ID FROM latest s LEFT JOIN {{ns}}.MEMBER_CURRENT c USING(GLOBAL_MEMBER_ID)
WHERE c.GLOBAL_MEMBER_ID IS NULL OR c.SOURCE_UPDATE_TS<s.SOURCE_UPDATE_TS
 OR (c.SOURCE_UPDATE_TS=s.SOURCE_UPDATE_TS AND c.SOURCE_SEQUENCE<s.SOURCE_SEQUENCE)
 OR (c.SOURCE_UPDATE_TS=s.SOURCE_UPDATE_TS AND c.SOURCE_SEQUENCE=s.SOURCE_SEQUENCE AND c.FACT_HASH<>s.FACT_HASH);

WITH physical AS (
 SELECT * FROM {{ns}}.TABLE_INDIA UNION ALL SELECT * FROM {{ns}}.TABLE_USA UNION ALL
 SELECT * FROM {{ns}}.TABLE_AUSTRALIA UNION ALL SELECT * FROM {{ns}}.TABLE_CANADA UNION ALL
 SELECT * FROM {{ns}}.TABLE_PHILIPPINES UNION ALL SELECT * FROM {{ns}}.TABLE_OTHER_COUNTRIES
)
SELECT GLOBAL_MEMBER_ID FROM physical
WHERE $VERIFY_BATCH='' OR GLOBAL_MEMBER_ID IN (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH)
GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*)<>1;

WITH physical AS (
 SELECT * FROM {{ns}}.TABLE_INDIA UNION ALL SELECT * FROM {{ns}}.TABLE_USA UNION ALL
 SELECT * FROM {{ns}}.TABLE_AUSTRALIA UNION ALL SELECT * FROM {{ns}}.TABLE_CANADA UNION ALL
 SELECT * FROM {{ns}}.TABLE_PHILIPPINES UNION ALL SELECT * FROM {{ns}}.TABLE_OTHER_COUNTRIES
), p AS (SELECT * FROM physical WHERE $VERIFY_BATCH='' OR GLOBAL_MEMBER_ID IN
 (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH)),
 c AS (SELECT * FROM {{ns}}.MEMBER_CURRENT WHERE $VERIFY_BATCH='' OR GLOBAL_MEMBER_ID IN
 (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$VERIFY_BATCH)),
 missing AS (SELECT * FROM c MINUS SELECT * FROM p),extra AS (SELECT * FROM p MINUS SELECT * FROM c)
SELECT GLOBAL_MEMBER_ID FROM missing UNION ALL SELECT GLOBAL_MEMBER_ID FROM extra;

SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_INDIA WHERE COUNTRY_CODE<>'IND'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_USA WHERE COUNTRY_CODE<>'USA'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_AUSTRALIA WHERE COUNTRY_CODE<>'AUS'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_CANADA WHERE COUNTRY_CODE<>'CAN'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_PHILIPPINES WHERE COUNTRY_CODE<>'PHL'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM {{ns}}.TABLE_OTHER_COUNTRIES WHERE COUNTRY_CODE IN ('IND','USA','AUS','CAN','PHL');

SELECT t.TRANSACTION_KEY FROM {{ns}}.REDEMPTION_TRANSACTION t
LEFT JOIN {{ns}}.MEMBER_CURRENT c ON t.GLOBAL_MEMBER_ID=c.GLOBAL_MEMBER_ID
LEFT JOIN {{ns}}.STG_REDEMPTION_RECORD s ON t.SOURCE_RECORD_ID=s.RECORD_ID
WHERE ($VERIFY_BATCH='' OR t.TRANSACTION_KEY IN (SELECT TRANSACTION_KEY FROM {{ns}}.STG_REDEMPTION_RECORD WHERE BATCH_ID=$VERIFY_BATCH))
AND (c.GLOBAL_MEMBER_ID IS NULL OR s.RECORD_ID IS NULL OR s.VALIDATION_STATUS<>'VALID' OR t.FACT_HASH<>s.FACT_HASH
 OR t.FACT_HASH<>SHA2(TO_JSON(ARRAY_CONSTRUCT(t.SOURCE_SYSTEM,t.SOURCE_MEMBER_ID,t.GLOBAL_MEMBER_ID,
 t.TXN_ID,t.TXN_DATE,t.PARTNER,t.MILES_REDEEMED,t.STATUS)),256));

WITH docs AS (
 SELECT RAW_RECORD_ID,BATCH_ID,COUNT_IF(RECORD_KIND='DOCUMENT') AS D,COUNT_IF(RECORD_KIND='ITEM') AS I
 FROM {{ns}}.STG_REDEMPTION_RECORD GROUP BY RAW_RECORD_ID,BATCH_ID
)
SELECT r.RAW_RECORD_ID FROM {{ns}}.RAW_REDEMPTION_FEED r JOIN docs d USING(RAW_RECORD_ID,BATCH_ID)
WHERE ($VERIFY_BATCH='' OR r.BATCH_ID=$VERIFY_BATCH) AND
 (d.D<>1 OR COALESCE(d.I,0)<>COALESCE(ARRAY_SIZE(r.PAYLOAD:redemptions),0));
