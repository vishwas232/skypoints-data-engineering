-- Operational aggregates, NOT zero-row invariant queries. Run after writers finish.
SELECT FEED_TYPE,SOURCE_SYSTEM,STATUS,COUNT(*) AS BATCHES,
 SUM(INPUT_ROWS) AS RAW_ROWS,MAX(FINISHED_AT) AS LAST_FINISHED_AT
FROM SKYPOINTS.INGEST_BATCH GROUP BY FEED_TYPE,SOURCE_SYSTEM,STATUS;

SELECT 'MEMBER' AS FEED_TYPE,VALIDATION_STATUS,COUNT(*) AS RECORDS
FROM SKYPOINTS.STG_MEMBER_PROFILE GROUP BY VALIDATION_STATUS
UNION ALL
SELECT 'REDEMPTION_DOCUMENT',VALIDATION_STATUS,COUNT(*)
FROM SKYPOINTS.STG_REDEMPTION_RECORD WHERE RECORD_KIND='DOCUMENT' GROUP BY VALIDATION_STATUS
UNION ALL
SELECT 'REDEMPTION_ITEM',VALIDATION_STATUS,COUNT(*)
FROM SKYPOINTS.STG_REDEMPTION_RECORD WHERE RECORD_KIND='ITEM' GROUP BY VALIDATION_STATUS;

SELECT FEED_TYPE,ERROR_CODE,COUNT(*) AS QUARANTINE_RECORDS,MIN(REJECTED_AT) AS OLDEST_CURRENT_REJECTION
FROM SKYPOINTS.REJECTED_RECORD GROUP BY FEED_TYPE,ERROR_CODE;

SELECT COUNTRY_CODE,COUNT(*) AS CURRENT_MEMBERS FROM SKYPOINTS.MEMBER_CURRENT GROUP BY COUNTRY_CODE;

SELECT STATUS,COUNT(*) AS TRANSACTIONS,SUM(MILES_REDEEMED) AS REPORTED_MILES
FROM SKYPOINTS.REDEMPTION_TRANSACTION GROUP BY STATUS;
