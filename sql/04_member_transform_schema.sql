-- Explicitly approved ordering for legacy files lacking row-level versions.
-- A timestamp is a source snapshot's business update time, NOT load time.
-- Row-level RAW metadata takes precedence. One immutable approval per batch.
CREATE TABLE IF NOT EXISTS MEMBER_BATCH_VERSION (
    BATCH_ID VARCHAR(100) NOT NULL,
    SOURCE_UPDATE_TS TIMESTAMP_NTZ NOT NULL,
    SOURCE_SEQUENCE NUMBER(38,0) NOT NULL DEFAULT 0,
    APPROVED_BY VARCHAR(255) NOT NULL,
    APPROVED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS MEMBER_TRANSFORM_RUN (
    RUN_ID VARCHAR(64) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    AS_OF_DATE DATE NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    INPUT_ROWS NUMBER NOT NULL,
    ACCEPTED_ROWS NUMBER NOT NULL,
    REJECTED_ROWS NUMBER NOT NULL,
    WINNING_ROWS NUMBER NOT NULL,
    SUPERSEDED_ROWS NUMBER NOT NULL,
    COMPLETED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
