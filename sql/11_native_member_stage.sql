-- All work is bounded to the requested raw batch. No history is fetched into Python.
DELETE FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$BATCH_ID;
INSERT INTO {{ns}}.STG_MEMBER_PROFILE
WITH fields AS (
 SELECT r.*,b.SOURCE_FORMAT,b.DOB_FORMAT,b.ENFORCE_NAME_KEY,
 b.SOURCE_UPDATE_TS AS B_TS,b.SOURCE_SEQUENCE AS B_SEQ,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Member_Id,PAYLOAD:Member_ID,PAYLOAD:"Member ID",PAYLOAD:ID,PAYLOAD:"Unique ID")) AS ID_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Member_Name,PAYLOAD:"Member Name",PAYLOAD:Name)) AS NAME_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Enrollment_Date,PAYLOAD:EnrollmentDate,PAYLOAD:"Date of Enrollment")) AS ENROLL_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Last_Flight_Date,PAYLOAD:FlightDate,PAYLOAD:"Flight Date",PAYLOAD:"Date of Flight")) AS FLIGHT_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Tier_Code,PAYLOAD:TierCode,PAYLOAD:"Tier Type")) AS TIER_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Agent_Name,PAYLOAD:AgentName)) AS AGENT_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:State,PAYLOAD:StateCode)) AS STATE_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Country,PAYLOAD:CountryCode,TO_VARIANT(SOURCE_COUNTRY))) AS COUNTRY_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Post_Code,PAYLOAD:PostCode,PAYLOAD:Postcode,PAYLOAD:"Post Code")) AS POST_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:DOB,PAYLOAD:Date_of_Birth,PAYLOAD:"Date of Birth")) AS DOB_VALUE,
 {{ns}}.CLEAN_TEXT(COALESCE(PAYLOAD:Is_Active,PAYLOAD:IsActive,PAYLOAD:"Active Member")) AS ACTIVE_VALUE,
 {{ns}}.CLEAN_TEXT(PAYLOAD:Source_Update_Ts) AS ROW_TS,
 {{ns}}.CLEAN_TEXT(PAYLOAD:Source_Sequence) AS ROW_SEQ
 FROM {{ns}}.RAW_MEMBER_PROFILE r JOIN {{ns}}.INGEST_BATCH b ON r.BATCH_ID=b.BATCH_ID
 WHERE r.BATCH_ID=$BATCH_ID
), maps AS (
 SELECT SOURCE_SYSTEM,SOURCE_MEMBER_ID,MIN(GLOBAL_MEMBER_ID) AS GID,COUNT(*) AS MAP_COUNT
 FROM {{ns}}.MEMBER_IDENTITY_MAP GROUP BY SOURCE_SYSTEM,SOURCE_MEMBER_ID
), normalized AS (
 SELECT f.*,m.GID,m.MAP_COUNT,
 {{ns}}.MEMBER_DATE(ENROLL_VALUE,SOURCE_FORMAT,DOB_FORMAT,'ENROLL') AS ENROLL_DATE,
 {{ns}}.MEMBER_DATE(FLIGHT_VALUE,SOURCE_FORMAT,DOB_FORMAT,'FLIGHT') AS FLIGHT_DATE,
 {{ns}}.MEMBER_DATE(DOB_VALUE,SOURCE_FORMAT,DOB_FORMAT,'DOB') AS BIRTH_DATE,
 CASE UPPER(COUNTRY_VALUE) WHEN 'IN' THEN 'IND' WHEN 'IND' THEN 'IND'
 WHEN 'US' THEN 'USA' WHEN 'USA' THEN 'USA' WHEN 'AU' THEN 'AUS' WHEN 'AUS' THEN 'AUS'
 WHEN 'CA' THEN 'CAN' WHEN 'CAN' THEN 'CAN' WHEN 'PH' THEN 'PHL' WHEN 'PHIL' THEN 'PHL'
 WHEN 'PHL' THEN 'PHL' WHEN 'GB' THEN 'GBR' WHEN 'GBR' THEN 'GBR'
 WHEN 'NZ' THEN 'NZL' WHEN 'NZL' THEN 'NZL' END AS COUNTRY,
 CASE UPPER(ACTIVE_VALUE) WHEN 'A' THEN 'A' WHEN 'Y' THEN 'A' WHEN 'I' THEN 'I' WHEN 'N' THEN 'I' END AS ACTIVE_FLAG,
 IFF(ROW_TS IS NULL,B_TS,TRY_TO_TIMESTAMP_NTZ(ROW_TS,'YYYY-MM-DD"T"HH24:MI:SS')) AS VERSION_TS,
 IFF(ROW_SEQ IS NULL,B_SEQ,IFF(REGEXP_LIKE(ROW_SEQ,'[0-9]{1,38}'),TRY_TO_NUMBER(ROW_SEQ),NULL)) AS VERSION_SEQ
 FROM fields f LEFT JOIN maps m ON f.SOURCE_SYSTEM=m.SOURCE_SYSTEM AND f.ID_VALUE=m.SOURCE_MEMBER_ID
), hashed AS (
 SELECT n.*,{{ns}}.AGE_ON(BIRTH_DATE,$AS_OF::DATE) AS YEARS,
 SHA2(TO_JSON(ARRAY_CONSTRUCT(SOURCE_SYSTEM,ID_VALUE,GID,NAME_VALUE,ENROLL_DATE,FLIGHT_DATE,
 TIER_VALUE,AGENT_VALUE,STATE_VALUE,COUNTRY,POST_VALUE,BIRTH_DATE,ACTIVE_FLAG)),256) AS F_HASH
 FROM normalized n
), name_owners AS (
 SELECT UPPER(c.MEMBER_NAME) AS NK,MIN(c.GLOBAL_MEMBER_ID) AS OWNER_ID,COUNT(DISTINCT c.GLOBAL_MEMBER_ID) AS OWNERS
 FROM {{ns}}.MEMBER_CURRENT c JOIN (SELECT DISTINCT UPPER(NAME_VALUE) AS NK FROM hashed) n
 ON UPPER(c.MEMBER_NAME)=n.NK GROUP BY UPPER(c.MEMBER_NAME)
), checked AS (
 SELECT h.*,
 ROW_NUMBER() OVER(PARTITION BY h.SOURCE_SYSTEM,h.ID_VALUE,h.F_HASH,h.VERSION_TS,h.VERSION_SEQ ORDER BY h.SOURCE_ROW_NUMBER,h.RAW_RECORD_ID) AS COPY_NUMBER,
 COUNT(DISTINCT F_HASH) OVER(PARTITION BY GID,VERSION_TS,VERSION_SEQ) AS VERSION_FACTS,
 COUNT(DISTINCT GID) OVER(PARTITION BY UPPER(NAME_VALUE)) AS NAME_IDS,
 c.GLOBAL_MEMBER_ID AS OLD_GID,c.FACT_HASH AS OLD_HASH,c.SOURCE_UPDATE_TS AS OLD_TS,c.SOURCE_SEQUENCE AS OLD_SEQ,
 (COALESCE(o.OWNERS,0)>1 OR (o.OWNERS=1 AND o.OWNER_ID<>h.GID)) AS NAME_TAKEN
 FROM hashed h LEFT JOIN {{ns}}.MEMBER_CURRENT c ON h.GID=c.GLOBAL_MEMBER_ID
 LEFT JOIN name_owners o ON UPPER(h.NAME_VALUE)=o.NK
), errors AS (
 SELECT x.*,ARRAY_CAT(COALESCE(PAYLOAD:_parse_errors::ARRAY,ARRAY_CONSTRUCT()),ARRAY_CONSTRUCT_COMPACT(
 IFF(ID_VALUE IS NULL,'MISSING_MEMBER_ID',NULL),IFF(LENGTH(ID_VALUE)>18,'MEMBER_ID_TOO_LONG',NULL),
 IFF(NAME_VALUE IS NULL,'MISSING_MEMBER_NAME',NULL),IFF(LENGTH(NAME_VALUE)>255,'MEMBER_NAME_TOO_LONG',NULL),
 IFF(TYPEOF(COALESCE(PAYLOAD:Member_Name,PAYLOAD:"Member Name",PAYLOAD:Name)) NOT IN ('VARCHAR','NULL_VALUE'),'INVALID_NAME_TYPE',NULL),
 IFF(ENROLL_VALUE IS NULL,'MISSING_ENROLLMENT_DATE',NULL),IFF(ENROLL_VALUE IS NOT NULL AND ENROLL_DATE IS NULL,'INVALID_ENROLLMENT_DATE',NULL),
 IFF(FLIGHT_VALUE IS NOT NULL AND FLIGHT_DATE IS NULL,'INVALID_FLIGHT_DATE',NULL),
 IFF(DOB_VALUE IS NOT NULL AND BIRTH_DATE IS NULL,'INVALID_DOB',NULL),
 IFF(ENROLL_DATE>$AS_OF::DATE OR FLIGHT_DATE>$AS_OF::DATE OR BIRTH_DATE>$AS_OF::DATE,'FUTURE_DATE',NULL),
 IFF(BIRTH_DATE>ENROLL_DATE,'DOB_AFTER_ENROLLMENT',NULL),IFF(FLIGHT_DATE<ENROLL_DATE,'FLIGHT_BEFORE_ENROLLMENT',NULL),
 IFF(YEARS<0 OR YEARS>130,'AGE_OUT_OF_RANGE',NULL),IFF(COUNTRY IS NULL,'INVALID_COUNTRY',NULL),
 IFF(LENGTH(TIER_VALUE)>5,'TIER_TOO_LONG',NULL),IFF(LENGTH(AGENT_VALUE)>255,'AGENT_TOO_LONG',NULL),
 IFF(LENGTH(STATE_VALUE)>5,'STATE_TOO_LONG',NULL),
 IFF(POST_VALUE IS NOT NULL AND NOT REGEXP_LIKE(POST_VALUE,'[0-9]{1,5}'),'INVALID_POST_CODE',NULL),
 IFF(ACTIVE_VALUE IS NOT NULL AND ACTIVE_FLAG IS NULL,'INVALID_ACTIVE_FLAG',NULL),
 IFF(COALESCE(MAP_COUNT,0)<>1 OR GID IS NULL OR LENGTH(GID)>100,'UNRESOLVED_OR_AMBIGUOUS_IDENTITY',NULL),
 IFF(VERSION_TS IS NULL OR VERSION_SEQ IS NULL OR VERSION_TS::DATE>$AS_OF::DATE,'INVALID_SOURCE_VERSION',NULL),
 IFF(COPY_NUMBER>1,'DUPLICATE_SOURCE_RECORD',NULL),
 IFF(GID IS NOT NULL AND VERSION_FACTS>1,'CONFLICTING_MEMBER_VERSION',NULL),
 IFF(OLD_GID IS NOT NULL AND VERSION_TS=OLD_TS AND VERSION_SEQ=OLD_SEQ AND F_HASH<>OLD_HASH,'CONFLICTING_MEMBER_VERSION',NULL),
 IFF(ENFORCE_NAME_KEY AND (NAME_IDS>1 OR NAME_TAKEN),'DUPLICATE_MEMBER_NAME',NULL)
 )) AS E FROM checked x
)
SELECT RAW_RECORD_ID,BATCH_ID,SOURCE_SYSTEM,ID_VALUE,GID,NAME_VALUE,ENROLL_DATE,FLIGHT_DATE,
 TIER_VALUE,AGENT_VALUE,STATE_VALUE,COUNTRY,POST_VALUE,BIRTH_DATE,
 IFF(YEARS BETWEEN 0 AND 130,YEARS,NULL),DATEDIFF(day,FLIGHT_DATE,$AS_OF::DATE)>90,ACTIVE_FLAG,
 VERSION_TS,VERSION_SEQ,F_HASH,IFF(ARRAY_SIZE(E)=0,'VALID','REJECTED'),E,$AS_OF::DATE,CURRENT_TIMESTAMP()
FROM errors;
