CREATE OR REPLACE FUNCTION {{ns}}.CLEAN_TEXT(V VARIANT) RETURNS VARCHAR
 LANGUAGE SQL AS $$ IFF(TYPEOF(V) IN ('VARCHAR','INTEGER','DECIMAL','DOUBLE'),
 IFF(UPPER(TRIM(V::VARCHAR)) IN ('','NULL','NONE'),NULL,TRIM(V::VARCHAR)),NULL) $$;
CREATE OR REPLACE FUNCTION {{ns}}.MEMBER_DATE(V VARCHAR,F VARCHAR,D VARCHAR,K VARCHAR) RETURNS DATE
 LANGUAGE SQL AS $$ CASE
 WHEN REGEXP_LIKE(V,'[0-9]{4}-[0-9]{2}-[0-9]{2}') THEN TRY_TO_DATE(V,'YYYY-MM-DD')
 WHEN REGEXP_LIKE(V,'[0-9]{4}-[0-9]{2}-[0-9]{2}T00:00:00([.]0+)?') THEN TRY_TO_DATE(LEFT(V,10),'YYYY-MM-DD')
 WHEN NOT REGEXP_LIKE(V,'[0-9]{7,8}') THEN NULL
 WHEN K='DOB' THEN TRY_TO_DATE(LPAD(V,8,'0'),D)
 WHEN F='EXCEL_US' THEN TRY_TO_DATE(LPAD(V,8,'0'),'MMDDYYYY')
 ELSE TRY_TO_DATE(V,'YYYYMMDD') END $$;
CREATE OR REPLACE FUNCTION {{ns}}.AGE_ON(D DATE,A DATE) RETURNS INTEGER
 LANGUAGE SQL AS $$ DATEDIFF(year,D,A)-IFF(TO_CHAR(A,'MMDD')<TO_CHAR(D,'MMDD'),1,0) $$;
CREATE OR REPLACE VIEW {{ns}}.REDEMPTION_MEMBER_DETAIL AS
 SELECT t.*,m.MEMBER_NAME,m.COUNTRY_CODE AS CURRENT_COUNTRY_CODE,m.TIER_CODE AS CURRENT_TIER_CODE
 FROM {{ns}}.REDEMPTION_TRANSACTION t JOIN {{ns}}.MEMBER_CURRENT m USING(GLOBAL_MEMBER_ID);
