DELETE FROM {{ns}}.STG_REDEMPTION_RECORD WHERE BATCH_ID=$BATCH_ID;
INSERT INTO {{ns}}.STG_REDEMPTION_RECORD
WITH maps AS (
 SELECT SOURCE_SYSTEM,SOURCE_MEMBER_ID,MIN(GLOBAL_MEMBER_ID) AS GID,COUNT(*) AS N
 FROM {{ns}}.MEMBER_IDENTITY_MAP GROUP BY SOURCE_SYSTEM,SOURCE_MEMBER_ID
), member_counts AS (
 SELECT GLOBAL_MEMBER_ID,COUNT(*) AS N FROM {{ns}}.MEMBER_CURRENT GROUP BY GLOBAL_MEMBER_ID
), fields AS (
 SELECT r.*,b.SOURCE_UPDATE_TS AS B_TS,b.SOURCE_SEQUENCE AS B_SEQ,b.ALLOW_TRANSACTION_UPDATES,
 {{ns}}.CLEAN_TEXT(PAYLOAD:member_id) AS MID,{{ns}}.CLEAN_TEXT(PAYLOAD:feed_date) AS FD
 FROM {{ns}}.RAW_REDEMPTION_FEED r JOIN {{ns}}.INGEST_BATCH b ON r.BATCH_ID=b.BATCH_ID
 WHERE r.BATCH_ID=$BATCH_ID
), documents AS (
 SELECT f.*,m.GID,m.N AS MAP_N,c.N AS MEMBER_N,
 CASE WHEN REGEXP_LIKE(FD,'[0-9]{8}') THEN TRY_TO_DATE(FD,'YYYYMMDD')
 WHEN REGEXP_LIKE(FD,'[0-9]{4}-[0-9]{2}-[0-9]{2}') THEN TRY_TO_DATE(FD,'YYYY-MM-DD') END AS F_DATE
 FROM fields f LEFT JOIN maps m ON f.SOURCE_SYSTEM=m.SOURCE_SYSTEM AND f.MID=m.SOURCE_MEMBER_ID
 LEFT JOIN member_counts c ON m.GID=c.GLOBAL_MEMBER_ID
), doc_errors AS (
 SELECT d.*,ARRAY_CONSTRUCT_COMPACT(
 IFF(NOT IS_OBJECT(PAYLOAD),'INVALID_DOCUMENT_OBJECT',NULL),
 IFF(MID IS NULL OR LENGTH(MID)>18,'INVALID_MEMBER_ID',NULL),
 IFF(F_DATE IS NULL,'INVALID_FEED_DATE',NULL),IFF(F_DATE>$AS_OF::DATE,'FUTURE_FEED_DATE',NULL),
 IFF(NOT COALESCE(IS_ARRAY(PAYLOAD:redemptions),FALSE),'INVALID_REDEMPTIONS_ARRAY',NULL),
 IFF(COALESCE(MAP_N,0)<>1 OR GID IS NULL,'UNRESOLVED_OR_AMBIGUOUS_IDENTITY',NULL),
 IFF(COALESCE(MEMBER_N,0)<>1,'MEMBER_NOT_CURRENT_OR_AMBIGUOUS',NULL)
 ) AS DE FROM documents d
), item_fields AS (
 SELECT d.*,f.INDEX AS IDX,f.VALUE AS ITEM,
 {{ns}}.CLEAN_TEXT(f.VALUE:txn_id) AS TID,{{ns}}.CLEAN_TEXT(f.VALUE:txn_date) AS TD,
 {{ns}}.CLEAN_TEXT(f.VALUE:partner) AS PARTNER_VALUE,UPPER({{ns}}.CLEAN_TEXT(f.VALUE:status)) AS STATUS_VALUE,
 IFF(TYPEOF(f.VALUE:miles_redeemed)='INTEGER',TRY_TO_DECIMAL(f.VALUE:miles_redeemed::VARCHAR,18,0),NULL) AS MILES,
 IFF(f.VALUE:source_update_ts IS NULL,B_TS,TRY_TO_TIMESTAMP_NTZ(f.VALUE:source_update_ts::VARCHAR,'YYYY-MM-DD"T"HH24:MI:SS')) AS V_TS,
 IFF(f.VALUE:source_sequence IS NULL,B_SEQ,IFF(REGEXP_LIKE(f.VALUE:source_sequence::VARCHAR,'[0-9]{1,38}'),TRY_TO_NUMBER(f.VALUE:source_sequence::VARCHAR),NULL)) AS V_SEQ
 FROM doc_errors d,LATERAL FLATTEN(INPUT=>IFF(IS_ARRAY(d.PAYLOAD:redemptions),d.PAYLOAD:redemptions,PARSE_JSON('[]'))) f
), item_dates AS (
 SELECT f.*,CASE WHEN REGEXP_LIKE(TD,'[0-9]{8}') THEN TRY_TO_DATE(TD,'YYYYMMDD')
 WHEN REGEXP_LIKE(TD,'[0-9]{4}-[0-9]{2}-[0-9]{2}') THEN TRY_TO_DATE(TD,'YYYY-MM-DD') END AS T_DATE,
 SHA2(TO_JSON(ARRAY_CONSTRUCT(SOURCE_SYSTEM,TID)),256) AS T_KEY
 FROM item_fields f
), hashed AS (
 SELECT f.*,SHA2(TO_JSON(ARRAY_CONSTRUCT(SOURCE_SYSTEM,MID,GID,TID,T_DATE,PARTNER_VALUE,MILES,STATUS_VALUE)),256) AS F_HASH
 FROM item_dates f
), checked AS (
 SELECT h.*,COUNT(DISTINCT F_HASH) OVER(PARTITION BY T_KEY,V_TS,V_SEQ) AS VERSION_FACTS,
 t.TRANSACTION_KEY AS OLD_KEY,t.GLOBAL_MEMBER_ID AS OLD_GID,t.FACT_HASH AS OLD_HASH,
 t.SOURCE_UPDATE_TS AS OLD_TS,t.SOURCE_SEQUENCE AS OLD_SEQ
 FROM hashed h LEFT JOIN {{ns}}.REDEMPTION_TRANSACTION t ON h.T_KEY=t.TRANSACTION_KEY
), item_errors AS (
 SELECT x.*,ARRAY_CAT(DE,ARRAY_CONSTRUCT_COMPACT(
 IFF(NOT IS_OBJECT(ITEM),'INVALID_TRANSACTION_OBJECT',NULL),
 IFF(TID IS NULL OR LENGTH(TID)>100 OR TYPEOF(ITEM:txn_id)<>'VARCHAR','INVALID_TXN_ID',NULL),
 IFF(T_DATE IS NULL,'INVALID_TXN_DATE',NULL),IFF(T_DATE>F_DATE OR T_DATE>$AS_OF::DATE,'TRANSACTION_AFTER_FEED_OR_PROCESSING_DATE',NULL),
 IFF(PARTNER_VALUE IS NULL OR LENGTH(PARTNER_VALUE)>255 OR TYPEOF(ITEM:partner)<>'VARCHAR','INVALID_PARTNER',NULL),
 IFF(STATUS_VALUE IS NULL OR STATUS_VALUE NOT IN ('PENDING','COMPLETED','CANCELLED','FAILED'),'INVALID_STATUS',NULL),
 IFF(MILES IS NULL OR MILES<=0,'INVALID_MILES_REDEEMED',NULL),
 IFF(V_TS IS NULL OR V_SEQ IS NULL OR V_TS::DATE>$AS_OF::DATE,'INVALID_SOURCE_VERSION',NULL),
 IFF(VERSION_FACTS>1,'CONFLICTING_TRANSACTION_VERSION',NULL),
 IFF(OLD_KEY IS NOT NULL AND OLD_GID<>GID,'TRANSACTION_IDENTITY_CONFLICT',NULL),
 IFF(OLD_KEY IS NOT NULL AND OLD_HASH<>F_HASH AND NOT ALLOW_TRANSACTION_UPDATES,'TRANSACTION_UPDATE_NOT_AUTHORIZED',NULL),
 IFF(OLD_KEY IS NOT NULL AND OLD_HASH<>F_HASH AND V_TS=OLD_TS AND V_SEQ=OLD_SEQ,'CONFLICTING_TRANSACTION_VERSION',NULL)
 )) AS E FROM checked x
)
SELECT SHA2(RAW_RECORD_ID||'|DOC',256),RAW_RECORD_ID,BATCH_ID,'DOCUMENT',-1,SOURCE_SYSTEM,MID,GID,
 F_DATE,NULL,NULL,NULL,NULL,NULL,NULL,B_TS,B_SEQ,NULL,
 IFF(ARRAY_SIZE(DE)=0,'VALID','REJECTED'),DE,CURRENT_TIMESTAMP() FROM doc_errors
UNION ALL
SELECT SHA2(RAW_RECORD_ID||'|'||IDX::VARCHAR,256),RAW_RECORD_ID,BATCH_ID,'ITEM',IDX,SOURCE_SYSTEM,MID,GID,
 F_DATE,T_KEY,TID,T_DATE,PARTNER_VALUE,MILES,STATUS_VALUE,V_TS,V_SEQ,F_HASH,
 IFF(ARRAY_SIZE(E)=0,'VALID','REJECTED'),E,CURRENT_TIMESTAMP() FROM item_errors;
