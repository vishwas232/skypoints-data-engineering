-- Each statement must return zero rows. No sample-specific expected row counts.
SELECT BATCH_ID FROM SKYPOINTS.INGEST_BATCH GROUP BY BATCH_ID HAVING COUNT(*)<>1;

SELECT RAW_RECORD_ID FROM SKYPOINTS.RAW_MEMBER_PROFILE GROUP BY RAW_RECORD_ID HAVING COUNT(*)<>1;

SELECT RAW_RECORD_ID FROM SKYPOINTS.RAW_REDEMPTION_FEED GROUP BY RAW_RECORD_ID HAVING COUNT(*)<>1;

SELECT r.RAW_RECORD_ID FROM SKYPOINTS.RAW_MEMBER_PROFILE r
LEFT JOIN SKYPOINTS.INGEST_BATCH b ON r.BATCH_ID=b.BATCH_ID
WHERE b.BATCH_ID IS NULL OR b.FEED_TYPE<>'MEMBER' OR b.SOURCE_SYSTEM<>r.SOURCE_SYSTEM;

SELECT r.RAW_RECORD_ID FROM SKYPOINTS.RAW_REDEMPTION_FEED r
LEFT JOIN SKYPOINTS.INGEST_BATCH b ON r.BATCH_ID=b.BATCH_ID
WHERE b.BATCH_ID IS NULL OR b.FEED_TYPE<>'REDEMPTION' OR b.SOURCE_SYSTEM<>r.SOURCE_SYSTEM;

WITH raw_counts AS (
 SELECT BATCH_ID,COUNT(*) AS N FROM SKYPOINTS.RAW_MEMBER_PROFILE GROUP BY BATCH_ID
 UNION ALL
 SELECT BATCH_ID,COUNT(*) AS N FROM SKYPOINTS.RAW_REDEMPTION_FEED GROUP BY BATCH_ID
), counts AS (SELECT BATCH_ID,SUM(N) AS N FROM raw_counts GROUP BY BATCH_ID)
SELECT b.BATCH_ID FROM SKYPOINTS.INGEST_BATCH b LEFT JOIN counts c ON b.BATCH_ID=c.BATCH_ID
WHERE b.STATUS='COMPLETED' AND
 (b.INPUT_ROWS<>COALESCE(c.N,0) OR b.INPUT_ROWS<>b.ACCEPTED_ROWS+b.REJECTED_ROWS
  OR b.FINISHED_AT IS NULL OR b.INPUT_ROWS<0 OR b.ACCEPTED_ROWS<0 OR b.REJECTED_ROWS<0);

SELECT BATCH_ID FROM SKYPOINTS.INGEST_BATCH
WHERE FEED_TYPE NOT IN ('MEMBER','REDEMPTION')
 OR STATUS NOT IN ('STARTED','COMPLETED','FAILED');

SELECT b.BATCH_ID FROM SKYPOINTS.INGEST_BATCH b
LEFT JOIN SKYPOINTS.MEMBER_TRANSFORM_RUN t ON b.BATCH_ID=t.BATCH_ID
WHERE b.STATUS='COMPLETED' AND b.FEED_TYPE='MEMBER' AND t.RUN_ID IS NULL;

SELECT b.BATCH_ID FROM SKYPOINTS.INGEST_BATCH b
LEFT JOIN SKYPOINTS.REDEMPTION_TRANSFORM_RUN t ON b.BATCH_ID=t.BATCH_ID
WHERE b.STATUS='COMPLETED' AND b.FEED_TYPE='REDEMPTION' AND t.RUN_ID IS NULL;

SELECT BATCH_ID FROM SKYPOINTS.INGEST_BATCH WHERE STATUS<>'COMPLETED';

SELECT SOURCE_SYSTEM,SOURCE_MEMBER_ID FROM SKYPOINTS.MEMBER_IDENTITY_MAP
GROUP BY SOURCE_SYSTEM,SOURCE_MEMBER_ID HAVING COUNT(*)<>1;

SELECT BATCH_ID FROM SKYPOINTS.MEMBER_BATCH_VERSION GROUP BY BATCH_ID HAVING COUNT(*)<>1;

SELECT s.RAW_RECORD_ID FROM SKYPOINTS.STG_MEMBER_PROFILE s
LEFT JOIN SKYPOINTS.RAW_MEMBER_PROFILE r ON s.RAW_RECORD_ID=r.RAW_RECORD_ID AND s.BATCH_ID=r.BATCH_ID
WHERE r.RAW_RECORD_ID IS NULL;

SELECT SOURCE_SYSTEM,SOURCE_MEMBER_ID FROM SKYPOINTS.MEMBER_IDENTITY_MAP
WHERE TRIM(SOURCE_SYSTEM)='' OR TRIM(SOURCE_MEMBER_ID)='' OR TRIM(GLOBAL_MEMBER_ID)=''
 OR TRIM(MAPPING_METHOD)='' OR VERIFIED_AT IS NULL;
