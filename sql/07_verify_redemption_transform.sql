-- Every statement must return ZERO rows. The CLI also executes these before commit.
SELECT TRANSACTION_KEY FROM SKYPOINTS.REDEMPTION_TRANSACTION
GROUP BY TRANSACTION_KEY HAVING COUNT(*)<>1;

SELECT RECORD_ID FROM SKYPOINTS.STG_REDEMPTION_RECORD
GROUP BY RECORD_ID HAVING COUNT(*)<>1;

SELECT RUN_ID FROM SKYPOINTS.REDEMPTION_TRANSFORM_RUN
GROUP BY RUN_ID HAVING COUNT(*)<>1;

SELECT RUN_ID FROM SKYPOINTS.REDEMPTION_TRANSFORM_RUN
WHERE STATUS<>'COMPLETED'
 OR DOCUMENT_ROWS<>ACCEPTED_DOCUMENTS+REJECTED_DOCUMENTS
 OR ITEM_ROWS<>ACCEPTED_ITEMS+REJECTED_ITEMS
 OR ACCEPTED_ITEMS<>NEW_TRANSACTIONS+REPLAY_ITEMS;

WITH latest AS (
 SELECT * FROM SKYPOINTS.REDEMPTION_TRANSFORM_RUN
 QUALIFY ROW_NUMBER() OVER (PARTITION BY BATCH_ID ORDER BY COMPLETED_AT DESC,RUN_ID DESC)=1
), staged AS (
 SELECT BATCH_ID,
 COUNT_IF(RECORD_KIND='DOCUMENT') AS D,
 COUNT_IF(RECORD_KIND='DOCUMENT' AND VALIDATION_STATUS='VALID') AS DV,
 COUNT_IF(RECORD_KIND='ITEM') AS I,
 COUNT_IF(RECORD_KIND='ITEM' AND VALIDATION_STATUS='VALID') AS IV
 FROM SKYPOINTS.STG_REDEMPTION_RECORD GROUP BY BATCH_ID
)
SELECT r.RUN_ID FROM latest r LEFT JOIN staged s ON r.BATCH_ID=s.BATCH_ID
WHERE r.DOCUMENT_ROWS<>COALESCE(s.D,0) OR r.ACCEPTED_DOCUMENTS<>COALESCE(s.DV,0)
 OR r.ITEM_ROWS<>COALESCE(s.I,0) OR r.ACCEPTED_ITEMS<>COALESCE(s.IV,0);

SELECT s.RECORD_ID FROM SKYPOINTS.STG_REDEMPTION_RECORD s
LEFT JOIN SKYPOINTS.REJECTED_RECORD r ON r.REJECTION_ID=s.RECORD_ID
 AND r.FEED_TYPE='REDEMPTION' AND r.BATCH_ID=s.BATCH_ID AND r.RAW_RECORD_ID=s.RAW_RECORD_ID
GROUP BY s.RECORD_ID,s.VALIDATION_STATUS
HAVING (s.VALIDATION_STATUS='REJECTED' AND COUNT(r.REJECTION_ID)<>1)
 OR (s.VALIDATION_STATUS='VALID' AND COUNT(r.REJECTION_ID)<>0);

SELECT t.TRANSACTION_KEY FROM SKYPOINTS.REDEMPTION_TRANSACTION t
LEFT JOIN SKYPOINTS.MEMBER_CURRENT m ON t.GLOBAL_MEMBER_ID=m.GLOBAL_MEMBER_ID
LEFT JOIN SKYPOINTS.MEMBER_IDENTITY_MAP i
 ON t.SOURCE_SYSTEM=i.SOURCE_SYSTEM AND t.SOURCE_MEMBER_ID=i.SOURCE_MEMBER_ID
GROUP BY t.TRANSACTION_KEY,t.GLOBAL_MEMBER_ID
HAVING COUNT(m.GLOBAL_MEMBER_ID)<>1 OR COUNT(i.GLOBAL_MEMBER_ID)<>1
 OR MIN(i.GLOBAL_MEMBER_ID)<>t.GLOBAL_MEMBER_ID;

SELECT t.TRANSACTION_KEY FROM SKYPOINTS.REDEMPTION_TRANSACTION t
LEFT JOIN SKYPOINTS.STG_REDEMPTION_RECORD s ON t.SOURCE_RECORD_ID=s.RECORD_ID
WHERE s.RECORD_ID IS NULL OR s.RECORD_KIND<>'ITEM' OR s.VALIDATION_STATUS<>'VALID'
 OR t.GLOBAL_MEMBER_ID IS NULL OR t.SOURCE_MEMBER_ID IS NULL
 OR t.FEED_DATE IS NULL OR t.TXN_DATE IS NULL OR t.PARTNER IS NULL OR t.STATUS IS NULL
 OR t.MILES_REDEEMED IS NULL OR t.MILES_REDEEMED<=0
 OR t.TXN_DATE>t.FEED_DATE
 OR t.TRANSACTION_KEY<>s.TRANSACTION_KEY OR t.RAW_RECORD_ID<>s.RAW_RECORD_ID
 OR t.LAST_BATCH_ID<>s.BATCH_ID;

SELECT s.RECORD_ID FROM SKYPOINTS.STG_REDEMPTION_RECORD s
LEFT JOIN SKYPOINTS.REDEMPTION_TRANSACTION t ON s.TRANSACTION_KEY=t.TRANSACTION_KEY
WHERE s.RECORD_KIND='ITEM' AND s.VALIDATION_STATUS='VALID'
 AND (t.TRANSACTION_KEY IS NULL OR s.GLOBAL_MEMBER_ID<>t.GLOBAL_MEMBER_ID
 OR s.SOURCE_SYSTEM<>t.SOURCE_SYSTEM OR s.SOURCE_MEMBER_ID<>t.SOURCE_MEMBER_ID
 OR s.TXN_ID<>t.TXN_ID OR s.TXN_DATE<>t.TXN_DATE OR s.PARTNER<>t.PARTNER
 OR s.MILES_REDEEMED<>t.MILES_REDEEMED OR s.STATUS<>t.STATUS);

SELECT s.RECORD_ID FROM SKYPOINTS.STG_REDEMPTION_RECORD s
LEFT JOIN SKYPOINTS.RAW_REDEMPTION_FEED r
 ON s.RAW_RECORD_ID=r.RAW_RECORD_ID AND s.BATCH_ID=r.BATCH_ID
WHERE r.RAW_RECORD_ID IS NULL;

WITH docs AS (
 SELECT RAW_RECORD_ID,BATCH_ID,COUNT(*) AS N FROM SKYPOINTS.STG_REDEMPTION_RECORD
 WHERE RECORD_KIND='DOCUMENT' GROUP BY RAW_RECORD_ID,BATCH_ID
)
SELECT r.RAW_RECORD_ID FROM SKYPOINTS.RAW_REDEMPTION_FEED r
JOIN (SELECT DISTINCT BATCH_ID FROM SKYPOINTS.REDEMPTION_TRANSFORM_RUN) b ON r.BATCH_ID=b.BATCH_ID
LEFT JOIN docs d ON r.RAW_RECORD_ID=d.RAW_RECORD_ID AND r.BATCH_ID=d.BATCH_ID
WHERE COALESCE(d.N,0)<>1;

WITH items AS (
 SELECT RAW_RECORD_ID,BATCH_ID,COUNT(*) AS N FROM SKYPOINTS.STG_REDEMPTION_RECORD
 WHERE RECORD_KIND='ITEM' GROUP BY RAW_RECORD_ID,BATCH_ID
)
SELECT d.RECORD_ID FROM SKYPOINTS.STG_REDEMPTION_RECORD d
JOIN SKYPOINTS.RAW_REDEMPTION_FEED r ON d.RAW_RECORD_ID=r.RAW_RECORD_ID AND d.BATCH_ID=r.BATCH_ID
LEFT JOIN items i ON d.RAW_RECORD_ID=i.RAW_RECORD_ID AND d.BATCH_ID=i.BATCH_ID
WHERE d.RECORD_KIND='DOCUMENT'
 AND COALESCE(i.N,0)<>IFF(IS_ARRAY(r.PAYLOAD:redemptions),ARRAY_SIZE(r.PAYLOAD:redemptions),0);
