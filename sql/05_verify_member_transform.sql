-- Every query must return ZERO rows. Also executed before Python commits.
SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.MEMBER_CURRENT
GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*) <> 1;

SELECT RAW_RECORD_ID FROM SKYPOINTS.STG_MEMBER_PROFILE
GROUP BY RAW_RECORD_ID HAVING COUNT(*) <> 1;

SELECT RUN_ID FROM SKYPOINTS.MEMBER_TRANSFORM_RUN
GROUP BY RUN_ID HAVING COUNT(*) <> 1;

SELECT * FROM SKYPOINTS.MEMBER_TRANSFORM_RUN
WHERE INPUT_ROWS <> ACCEPTED_ROWS + REJECTED_ROWS
   OR ACCEPTED_ROWS <> WINNING_ROWS + SUPERSEDED_ROWS;

WITH latest AS (
 SELECT * FROM SKYPOINTS.MEMBER_TRANSFORM_RUN
 QUALIFY ROW_NUMBER() OVER (PARTITION BY BATCH_ID ORDER BY COMPLETED_AT DESC,RUN_ID DESC)=1
), staged AS (
 SELECT BATCH_ID,COUNT(*) AS N,COUNT_IF(VALIDATION_STATUS='VALID') AS V
 FROM SKYPOINTS.STG_MEMBER_PROFILE GROUP BY BATCH_ID
)
SELECT r.RUN_ID FROM latest r LEFT JOIN staged s ON r.BATCH_ID=s.BATCH_ID
WHERE r.INPUT_ROWS<>COALESCE(s.N,0) OR r.ACCEPTED_ROWS<>COALESCE(s.V,0);

SELECT s.GLOBAL_MEMBER_ID FROM SKYPOINTS.STG_MEMBER_PROFILE s
LEFT JOIN SKYPOINTS.MEMBER_CURRENT c ON s.GLOBAL_MEMBER_ID=c.GLOBAL_MEMBER_ID
WHERE s.VALIDATION_STATUS='VALID' AND c.GLOBAL_MEMBER_ID IS NULL;

SELECT s.RAW_RECORD_ID FROM SKYPOINTS.STG_MEMBER_PROFILE s
LEFT JOIN SKYPOINTS.REJECTED_RECORD r
ON r.RAW_RECORD_ID=s.RAW_RECORD_ID AND r.BATCH_ID=s.BATCH_ID AND r.FEED_TYPE='MEMBER'
GROUP BY s.RAW_RECORD_ID,s.VALIDATION_STATUS
HAVING (s.VALIDATION_STATUS='REJECTED' AND COUNT(r.REJECTION_ID)<>1)
    OR (s.VALIDATION_STATUS='VALID' AND COUNT(r.REJECTION_ID)<>0);

SELECT c.GLOBAL_MEMBER_ID FROM SKYPOINTS.MEMBER_CURRENT c
LEFT JOIN (
  SELECT * FROM SKYPOINTS.STG_MEMBER_PROFILE WHERE VALIDATION_STATUS='VALID'
  QUALIFY ROW_NUMBER() OVER (PARTITION BY GLOBAL_MEMBER_ID
    ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RAW_RECORD_ID DESC)=1
) s ON c.GLOBAL_MEMBER_ID=s.GLOBAL_MEMBER_ID
WHERE s.RAW_RECORD_ID IS NULL OR c.WINNER_RAW_RECORD_ID IS NULL
   OR c.WINNER_RAW_RECORD_ID<>s.RAW_RECORD_ID
   OR c.COUNTRY_CODE<>s.COUNTRY_CODE;

WITH physical AS (
 SELECT * FROM SKYPOINTS.TABLE_INDIA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_USA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_AUSTRALIA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_CANADA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_PHILIPPINES UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_OTHER_COUNTRIES
)
SELECT GLOBAL_MEMBER_ID FROM physical GROUP BY GLOBAL_MEMBER_ID HAVING COUNT(*)<>1;

WITH physical AS (
 SELECT * FROM SKYPOINTS.TABLE_INDIA UNION ALL SELECT * FROM SKYPOINTS.TABLE_USA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_AUSTRALIA UNION ALL SELECT * FROM SKYPOINTS.TABLE_CANADA UNION ALL
 SELECT * FROM SKYPOINTS.TABLE_PHILIPPINES UNION ALL SELECT * FROM SKYPOINTS.TABLE_OTHER_COUNTRIES
), missing AS (SELECT * FROM SKYPOINTS.MEMBER_CURRENT MINUS SELECT * FROM physical),
extra AS (SELECT * FROM physical MINUS SELECT * FROM SKYPOINTS.MEMBER_CURRENT)
SELECT * FROM missing UNION ALL SELECT * FROM extra;

SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_INDIA WHERE COUNTRY_CODE<>'IND'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_USA WHERE COUNTRY_CODE<>'USA'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_AUSTRALIA WHERE COUNTRY_CODE<>'AUS'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_CANADA WHERE COUNTRY_CODE<>'CAN'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_PHILIPPINES WHERE COUNTRY_CODE<>'PHL'
UNION ALL SELECT GLOBAL_MEMBER_ID FROM SKYPOINTS.TABLE_OTHER_COUNTRIES WHERE COUNTRY_CODE IN ('IND','USA','AUS','CAN','PHL');
