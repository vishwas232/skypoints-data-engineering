-- SkyPoints assessment: Phase 2 schema only (Snowflake SQL)
-- Prerequisite: select your database with USE DATABASE <YOUR_DATABASE>;
-- This script creates objects; it does NOT ingest data.
CREATE SCHEMA IF NOT EXISTS SKYPOINTS;
USE SCHEMA SKYPOINTS;

-- One run per attempted file/batch. A file hash can identify identical replays.
CREATE TABLE IF NOT EXISTS INGEST_BATCH (
    BATCH_ID VARCHAR(100) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_FILE VARCHAR(1024),
    FILE_SHA256 VARCHAR(64),
    FEED_TYPE VARCHAR(30) NOT NULL,
    BUSINESS_DATE DATE,
    STARTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    FINISHED_AT TIMESTAMP_NTZ,
    STATUS VARCHAR(30) DEFAULT 'STARTED',
    INPUT_ROWS NUMBER(38,0) DEFAULT 0,
    ACCEPTED_ROWS NUMBER(38,0) DEFAULT 0,
    REJECTED_ROWS NUMBER(38,0) DEFAULT 0,
    ERROR_MESSAGE VARCHAR,
    CONSTRAINT PK_INGEST_BATCH PRIMARY KEY (BATCH_ID)
);

-- Preserve source values without parsing dates/correcting bad records.
-- Each record is a VARIANT object produced by an ingestion adapter.
CREATE TABLE IF NOT EXISTS RAW_MEMBER_PROFILE (
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_FILE VARCHAR(1024) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38,0),
    SOURCE_COUNTRY VARCHAR(10),
    SOURCE_UPDATE_TS TIMESTAMP_NTZ,
    SOURCE_SEQUENCE NUMBER(38,0),
    PAYLOAD VARIANT NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_RAW_MEMBER PRIMARY KEY (RAW_RECORD_ID)
);

CREATE TABLE IF NOT EXISTS RAW_REDEMPTION_FEED (
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_FILE VARCHAR(1024) NOT NULL,
    SOURCE_ROW_NUMBER NUMBER(38,0),
    PAYLOAD VARIANT NOT NULL,
    INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_RAW_REDEMPTION PRIMARY KEY (RAW_RECORD_ID)
);

-- Standardized data, including the required derived fields.
-- GLOBAL_MEMBER_ID must come from a verified member mapping; never assume
-- that a local ID in IND.xlsx equals the same ID in USA.xlsx.
CREATE TABLE IF NOT EXISTS STG_MEMBER_PROFILE (
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_MEMBER_ID VARCHAR(18),
    GLOBAL_MEMBER_ID VARCHAR(100),
    MEMBER_NAME VARCHAR(255),
    ENROLLMENT_DATE DATE,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE VARCHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE_CODE VARCHAR(5),
    COUNTRY_CODE VARCHAR(10),
    POST_CODE VARCHAR(20),
    DOB DATE,
    AGE NUMBER(3,0),
    STALE_MEMBER BOOLEAN,
    IS_ACTIVE VARCHAR(1),
    MEMBER_TYPE VARCHAR(1),
    SOURCE_UPDATE_TS TIMESTAMP_NTZ,
    SOURCE_SEQUENCE NUMBER(38,0),
    INGESTED_AT TIMESTAMP_NTZ,
    VALIDATION_STATUS VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    VALIDATION_ERRORS ARRAY,
    VALIDATED_AT TIMESTAMP_NTZ,
    CONSTRAINT PK_STG_MEMBER PRIMARY KEY (RAW_RECORD_ID)
);

-- Controlled mapping of source-local identities to global identities.
-- A matching member ID in different country files alone is NOT proof of identity.
CREATE TABLE IF NOT EXISTS MEMBER_IDENTITY_MAP (
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_MEMBER_ID VARCHAR(18) NOT NULL,
    GLOBAL_MEMBER_ID VARCHAR(100) NOT NULL,
    MAPPING_METHOD VARCHAR(50) NOT NULL,
    VERIFIED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_IDENTITY_MAP PRIMARY KEY (SOURCE_SYSTEM, SOURCE_MEMBER_ID)
);

-- Safe handling for records that fail validation, or lack a verified global ID.
CREATE TABLE IF NOT EXISTS REJECTED_RECORD (
    REJECTION_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    FEED_TYPE VARCHAR(30) NOT NULL,
    ERROR_CODE VARCHAR(100) NOT NULL,
    ERROR_DETAIL VARCHAR,
    REJECTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_REJECTION PRIMARY KEY (REJECTION_ID)
);

-- A single current row per globally identified member.
-- Latest-wins ordering is based on source-update timestamp and a source
-- supplied tie-breaker, not just ingestion time.
CREATE TABLE IF NOT EXISTS MEMBER_CURRENT (
    GLOBAL_MEMBER_ID VARCHAR(100) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    SOURCE_MEMBER_ID VARCHAR(18) NOT NULL,
    MEMBER_NAME VARCHAR(255) NOT NULL,
    ENROLLMENT_DATE DATE NOT NULL,
    LAST_FLIGHT_DATE DATE,
    TIER_CODE VARCHAR(5),
    AGENT_NAME VARCHAR(255),
    STATE_CODE VARCHAR(5),
    COUNTRY_CODE VARCHAR(10) NOT NULL,
    POST_CODE VARCHAR(20),
    DOB DATE,
    AGE NUMBER(3,0),
    STALE_MEMBER BOOLEAN,
    IS_ACTIVE VARCHAR(1),
    MEMBER_TYPE VARCHAR(1),
    SOURCE_UPDATE_TS TIMESTAMP_NTZ NOT NULL,
    SOURCE_SEQUENCE NUMBER(38,0),
    LAST_BATCH_ID VARCHAR(100) NOT NULL,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_MEMBER_CURRENT PRIMARY KEY (GLOBAL_MEMBER_ID)
);

-- Requested physical per-country targets, maintained from MEMBER_CURRENT.
-- CREATE TABLE LIKE copies structure, not data.
CREATE TABLE IF NOT EXISTS TABLE_INDIA LIKE MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS TABLE_USA LIKE MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS TABLE_AUSTRALIA LIKE MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS TABLE_CANADA LIKE MEMBER_CURRENT;
CREATE TABLE IF NOT EXISTS TABLE_PHILIPPINES LIKE MEMBER_CURRENT;

-- Queryable flat transaction table; one transaction can appear in many feeds.
CREATE TABLE IF NOT EXISTS REDEMPTION_TRANSACTION (
    TRANSACTION_KEY VARCHAR(200) NOT NULL,
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    TXN_ID VARCHAR(100) NOT NULL,
    GLOBAL_MEMBER_ID VARCHAR(100),
    SOURCE_MEMBER_ID VARCHAR(18),
    FEED_DATE DATE,
    TXN_DATE DATE,
    PARTNER VARCHAR(255),
    MILES_REDEEMED NUMBER(18,0),
    STATUS VARCHAR(30),
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    LAST_BATCH_ID VARCHAR(100) NOT NULL,
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_REDEMPTION_TXN PRIMARY KEY (TRANSACTION_KEY)
);

-- Auditable cross-country movement: populated by Phase 4 merge logic.
CREATE TABLE IF NOT EXISTS COUNTRY_MOVEMENT_AUDIT (
    MOVEMENT_ID VARCHAR(100) NOT NULL,
    GLOBAL_MEMBER_ID VARCHAR(100) NOT NULL,
    FROM_COUNTRY VARCHAR(10),
    TO_COUNTRY VARCHAR(10) NOT NULL,
    SOURCE_UPDATE_TS TIMESTAMP_NTZ NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    RECORDED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    CONSTRAINT PK_COUNTRY_MOVEMENT PRIMARY KEY (MOVEMENT_ID)
);

-- NOTE: Standard Snowflake tables do not enforce PRIMARY KEY / UNIQUE
