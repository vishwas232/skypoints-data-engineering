INSERT INTO {{ns}}.COUNTRY_MOVEMENT_AUDIT
 (MOVEMENT_ID,GLOBAL_MEMBER_ID,FROM_COUNTRY,TO_COUNTRY,BATCH_ID,RUN_ID,SOURCE_UPDATE_TS)
WITH incoming AS (
 SELECT * FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$BATCH_ID AND VALIDATION_STATUS='VALID'
 QUALIFY ROW_NUMBER() OVER(PARTITION BY GLOBAL_MEMBER_ID ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RAW_RECORD_ID DESC)=1
)
SELECT SHA2(TO_JSON(ARRAY_CONSTRUCT($RUN_ID,s.GLOBAL_MEMBER_ID,c.COUNTRY_CODE,s.COUNTRY_CODE)),256),
 s.GLOBAL_MEMBER_ID,c.COUNTRY_CODE,s.COUNTRY_CODE,s.BATCH_ID,$RUN_ID,s.SOURCE_UPDATE_TS
FROM incoming s JOIN {{ns}}.MEMBER_CURRENT c USING(GLOBAL_MEMBER_ID)
WHERE (s.SOURCE_UPDATE_TS>c.SOURCE_UPDATE_TS OR (s.SOURCE_UPDATE_TS=c.SOURCE_UPDATE_TS AND s.SOURCE_SEQUENCE>c.SOURCE_SEQUENCE))
 AND s.COUNTRY_CODE<>c.COUNTRY_CODE;

MERGE INTO {{ns}}.MEMBER_CURRENT c USING (
 SELECT GLOBAL_MEMBER_ID,SOURCE_SYSTEM,SOURCE_MEMBER_ID,MEMBER_NAME,ENROLLMENT_DATE,LAST_FLIGHT_DATE,
 TIER_CODE,AGENT_NAME,STATE_CODE,COUNTRY_CODE,POST_CODE,DOB,AGE,STALE_MEMBER,IS_ACTIVE,
 SOURCE_UPDATE_TS,SOURCE_SEQUENCE,FACT_HASH,RAW_RECORD_ID AS WINNER_RAW_RECORD_ID,
 BATCH_ID AS LAST_BATCH_ID,AS_OF_DATE,CURRENT_TIMESTAMP()::TIMESTAMP_NTZ AS UPDATED_AT
 FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$BATCH_ID AND VALIDATION_STATUS='VALID'
 QUALIFY ROW_NUMBER() OVER(PARTITION BY GLOBAL_MEMBER_ID ORDER BY SOURCE_UPDATE_TS DESC,SOURCE_SEQUENCE DESC,RAW_RECORD_ID DESC)=1
) s ON c.GLOBAL_MEMBER_ID=s.GLOBAL_MEMBER_ID
WHEN MATCHED AND (s.SOURCE_UPDATE_TS>c.SOURCE_UPDATE_TS OR
 (s.SOURCE_UPDATE_TS=c.SOURCE_UPDATE_TS AND s.SOURCE_SEQUENCE>c.SOURCE_SEQUENCE)) THEN UPDATE ALL BY NAME
WHEN NOT MATCHED THEN INSERT ALL BY NAME;

-- Refresh derived values for affected current members without changing business lineage.
UPDATE {{ns}}.MEMBER_CURRENT c SET AGE={{ns}}.AGE_ON(c.DOB,$AS_OF::DATE),
 STALE_MEMBER=DATEDIFF(day,c.LAST_FLIGHT_DATE,$AS_OF::DATE)>90,AS_OF_DATE=$AS_OF::DATE,
 UPDATED_AT=CURRENT_TIMESTAMP()
WHERE c.AS_OF_DATE<$AS_OF::DATE AND c.GLOBAL_MEMBER_ID IN
 (SELECT GLOBAL_MEMBER_ID FROM {{ns}}.STG_MEMBER_PROFILE WHERE BATCH_ID=$BATCH_ID AND VALIDATION_STATUS='VALID');
