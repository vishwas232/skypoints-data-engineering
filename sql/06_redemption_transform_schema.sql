-- Run separately after Phase 2 and Phase 4 DDL, in the selected database.
USE SCHEMA SKYPOINTS;
ALTER TABLE REDEMPTION_TRANSACTION ADD COLUMN IF NOT EXISTS SOURCE_RECORD_ID VARCHAR(64);

-- DOCUMENT rows (index -1) make malformed/empty envelopes auditable.
-- ITEM rows preserve every array position, including invalid array elements.
CREATE TABLE IF NOT EXISTS STG_REDEMPTION_RECORD (
    RECORD_ID VARCHAR(64) NOT NULL,
    RAW_RECORD_ID VARCHAR(100) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    RECORD_KIND VARCHAR(10) NOT NULL,
    ITEM_INDEX NUMBER(38,0) NOT NULL,
    RAW_SHA256 VARCHAR(64) NOT NULL,
    TRANSACTION_KEY VARCHAR(200),
    SOURCE_SYSTEM VARCHAR(100) NOT NULL,
    TXN_ID VARCHAR(100),
    GLOBAL_MEMBER_ID VARCHAR(100),
    SOURCE_MEMBER_ID VARCHAR(18),
    FEED_DATE DATE,
    TXN_DATE DATE,
    PARTNER VARCHAR(255),
    MILES_REDEEMED NUMBER(18,0),
    STATUS VARCHAR(30),
    VALIDATION_STATUS VARCHAR(20) NOT NULL,
    VALIDATION_ERRORS ARRAY NOT NULL,
    VALIDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);
CREATE TABLE IF NOT EXISTS REDEMPTION_TRANSFORM_RUN (
    RUN_ID VARCHAR(64) NOT NULL,
    BATCH_ID VARCHAR(100) NOT NULL,
    AS_OF_DATE DATE NOT NULL,
    STATUS VARCHAR(30) NOT NULL,
    DOCUMENT_ROWS NUMBER NOT NULL,
    ACCEPTED_DOCUMENTS NUMBER NOT NULL,
    REJECTED_DOCUMENTS NUMBER NOT NULL,
    ITEM_ROWS NUMBER NOT NULL,
    ACCEPTED_ITEMS NUMBER NOT NULL,
    REJECTED_ITEMS NUMBER NOT NULL,
    NEW_TRANSACTIONS NUMBER NOT NULL,
    REPLAY_ITEMS NUMBER NOT NULL,
    COMPLETED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Enrichment follows current canonical country/name after member movements.
-- No copying member attributes into historical transaction facts.
CREATE OR REPLACE VIEW REDEMPTION_MEMBER_DETAIL AS
SELECT t.*,m.MEMBER_NAME,m.COUNTRY_CODE AS CURRENT_COUNTRY_CODE,
       m.TIER_CODE AS CURRENT_TIER_CODE
FROM REDEMPTION_TRANSACTION t
JOIN MEMBER_CURRENT m ON t.GLOBAL_MEMBER_ID=m.GLOBAL_MEMBER_ID;
